def inline_images_to_files(src):
    """Replace base64 data URIs that are byte-identical to a file in assets/ with that file's URL."""
    by_hash = {}
    adir = os.path.join(ROOT, "assets")
    for n in os.listdir(adir):
        p = os.path.join(adir, n)
        if os.path.isfile(p):
            by_hash[hashlib.md5(open(p, "rb").read()).hexdigest()] = "/assets/" + n

    def swap(m):
        h = hashlib.md5(base64.b64decode(m.group(2))).hexdigest()
        return by_hash.get(h, m.group(0))
    return re.sub(r"data:image/(png|jpe?g|webp|gif);base64,([A-Za-z0-9+/=]+)", swap, src)


def process(fname, meta):
    p = os.path.join(ROOT, fname)
    src = open(p, encoding="utf-8").read()
    src = re.sub(re.escape(START) + r".*?" + re.escape(END) + r"\n?", "", src, flags=re.S)
    # drop the old per-page tags this block now owns
    for pat in [r'<meta name="description"[^>]*>\s*', r'<link rel="canonical"[^>]*>\s*',
                r'<meta property="og:[^"]+"[^>]*>\s*', r'<meta name="twitter:[^"]+"[^>]*>\s*',
                r'<meta name="robots"[^>]*>\s*', r'<meta name="theme-color"[^>]*>\s*']:
        src = re.sub(pat, "", src)
    src = re.sub(r"<title>.*?</title>", "<title>%s</title>" % html.escape(meta["title"], quote=False), src, count=1, flags=re.S)
    src = src.replace("</title>", "</title>\n" + block(fname, meta, src), 1)
    src = inline_images_to_files(src)
    open(p, "w", encoding="utf-8", newline="").write(src)
    return len(src)


def sitemap():
    today = datetime.date.today().isoformat()
    rows = []
    for fname, meta in PAGES.items():
        pri = "1.0" if meta["path"] == "/" else ("0.9" if fname in ("tryouts.html", "camps.html") else "0.7")
        rows.append("  <url><loc>%s%s</loc><lastmod>%s</lastmod><priority>%s</priority></url>" % (SITE, meta["path"], today, pri))
    xml = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n%s\n</urlset>\n' % "\n".join(rows)
    open(os.path.join(ROOT, "sitemap.xml"), "w", encoding="utf-8", newline="\n").write(xml)


if __name__ == "__main__":
    for fname, meta in PAGES.items():
        before = os.path.getsize(os.path.join(ROOT, fname))
        after = process(fname, meta)
        print("%-14s %4d KB -> %4d KB" % (fname, before // 1024, after // 1024))
    sitemap()
    print("sitemap.xml written")
